//! ACS instruction numbers (ACC's `pcd_t`), as stored in BEHAVIOR lumps.

macro_rules! pcodes {
    ($($name:ident = $n:expr,)*) => {
        $(pub const $name: u32 = $n;)*

        /// The pcode's name, for diagnostics.
        pub fn name(p: u32) -> &'static str {
            match p {
                $($n => stringify!($name),)*
                _ => "?",
            }
        }
    };
}

